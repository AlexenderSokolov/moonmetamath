import fs from 'node:fs';
import { resolve, join, relative } from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { coreClient, root } from '../bin/host.mjs';
import { createNotebook, restoreNotebook } from '../web/notebook.mjs';
import { verify } from './oracle.mjs';

const at = process.argv.indexOf('--out');
if (at < 0) throw new Error('Pass --out UNIQUE_DIRECTORY; run with Node --max-old-space-size=2048');
const out = resolve(root, process.argv[at + 1]);
if (fs.existsSync(out)) throw new Error('Output directory already exists');
fs.mkdirSync(out, { recursive: true });
const lock = JSON.parse(fs.readFileSync(join(root, 'benchmarks/databases.lock.json')));
const source = lock.files.find(x => x.id === 'set');
let bytes = fs.readFileSync(join(root, source.path));
assert.equal(createHash('sha256').update(bytes).digest('hex'), source.sha256);
const limits = { max_operations: 100000000 };
const bounded = request => fields => request({ ...fields, ...(['load', 'verify', 'start', 'create_goal', 'replay'].includes(fields.operation) ? { limits } : {}) });
const request = bounded(await coreClient());
const events = [];
function checked(operation, fields = {}) {
  const begin = performance.now();
  const r = request({ operation, ...fields });
  assert.equal(r.status, 'ok', JSON.stringify(r.diagnostics));
  events.push({ operation, milliseconds: performance.now() - begin, outcome: r.outcome, rss: process.memoryUsage().rss });
  fs.writeFileSync(join(out, 'progress.json'), JSON.stringify(events, null, 2));
  console.log(`${operation}: ${r.outcome ?? r.status}`);
  return r;
}
const loaded = checked('load', { entry: 'set.mm', sources: [{ source_id: 'set.mm', text: bytes.toString('latin1') }] });
bytes = null;
const database_id = loaded.data.database_id;
const report = checked('verify', { database_id });
assert.equal(report.outcome, 'valid');
assert.equal(report.data.verified_count, 48097);
const started = checked('start', { database_id, target_label: 'young2d' });
checked('rules', { database_id, target_label: 'young2d', query: 'wph', limit: 20 });
checked('preview', { session_id: started.data.session_id, label: 'wph' });
checked('close_session', { session_id: started.data.session_id });
// Repeat the exact formerly failing goal expression before the constructive case.
let original = checked('create_goal', { database_id, context_label: 'young2d', new_label: 'large-original-goal', goal: started.data.view.goal });
assert.deepEqual(original.data.goal, started.data.view.goal);
checked('unload_database', { database_id: original.data.database_id });
original = null;
const created = checked('create_goal', { database_id, context_label: 'young2d', new_label: 'large-syntax-goal', goal: ['wff', 'ph'] });
checked('unload_database', { database_id });
const session = checked('start', { database_id: created.data.database_id, target_label: created.data.target_label }).data.session_id;
checked('apply_label', { session_id: session, label: 'wph' });
checked('rewind', { session_id: session, successful_step_count: 0 });
checked('apply_label', { session_id: session, label: 'wph' });
assert.equal(checked('finish', { session_id: session }).outcome, 'valid');
const notebook = await createNotebook({ bundle: { entry: created.data.entry, sources: created.data.sources }, target_label: created.data.target_label, actions: [{ operation: 'apply_label', label: 'wph' }], completed: true });
const file = join(out, 'complete-work.json');
fs.writeFileSync(file, JSON.stringify(notebook));
const candidate = bounded(await coreClient());
const restored = await restoreNotebook(JSON.parse(fs.readFileSync(file, 'utf8')), candidate);
assert.equal(restored.view.state, 'complete');
assert.deepEqual(restored.view.stack, [['wff', 'ph']]);
const exported = candidate({ operation: 'export', session_id: restored.session_id, new_label: 'large-restored-export' });
assert.equal(exported.outcome, 'valid');
const proof = join(out, 'candidate.mm');
fs.writeFileSync(proof, exported.data.text);
assert.equal((await verify(proof, join(out, 'independent'))).status, 'valid');
checked('close_session', { session_id: session });
checked('unload_database', { database_id: created.data.database_id });
candidate({ operation: 'reset' });
const result = { pass: true, input_sha256: source.sha256, original_proofs: 48097, operation_limit: limits.max_operations, original_goal_creation: true, constructed_goal: ['wff', 'ph'], restored: true, independent: 'valid', peak_rss_kib: process.resourceUsage().maxRSS, notebook_bytes: fs.statSync(file).size, proof_bytes: fs.statSync(proof).size, events };
fs.writeFileSync(join(out, 'result.json'), JSON.stringify(result, null, 2));
console.log(JSON.stringify({ pass: true, evidence: relative(root, out) }));
